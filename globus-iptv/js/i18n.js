  GI.plural = function (n, key) {
    n = Math.abs(Math.round(Number(n) || 0));
    const forms = (PLURALS[GI.lang] || PLURALS.ru)[key];
    if (!forms) return key;
    if (GI.lang === "en") return forms[n === 1 ? 0 : 1];
    const d10 = n % 10, d100 = n % 100;
    if (d10 === 1 && d100 !== 11) return forms[0];
    if (d10 >= 2 && d10 <= 4 && (d100 < 12 || d100 > 14)) return forms[1];
    return forms[2];
  };

